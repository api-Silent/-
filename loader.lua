local function XOR(a, b)
    local result = 0
    local bit = 1

    while a > 0 or b > 0 do
        local x = a % 2
        local y = b % 2

        if x ~= y then
            result = result + bit
        end

        a = math.floor(a / 2)
        b = math.floor(b / 2)
        bit = bit * 2
    end

    return result
end

local function Decrypt(data)
    if #data % 2 ~= 0 then
        error("Invalid payload length", 0)
    end

    local output = {}

    for i = 1, #data, 2 do
        local byte = tonumber(data:sub(i, i + 1), 16)

        if not byte then
            error("Invalid payload data", 0)
        end

        output[#output + 1] = string.char(XOR(byte, 77))
    end

    return table.concat(output)
end

